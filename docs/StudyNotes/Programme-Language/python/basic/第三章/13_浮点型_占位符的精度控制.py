# 浮点数占位符的精度控制
# 也可以通过：%{m}.{n}f 的形式对展示的数据进行一些限制
# m 表示展示的总位数，位数不够会自动使用空格进行补全，但小于m的位数不会被截断；正数为右对齐，负数为左对齐；
# m 的总位数 = 整数位数 + 小数点 + 小数点后位数
# n 表示精度，有默认值6，表示小数点后6位，如设置值超过6，则会自动使用0进行补位；小于浮点数本身的精度会被截断，会四舍五入；

print("%.2f" % 3.141592653589793) # 3.14
print("%.3f" % 3.141592653589793) # 3.142（进行了截断并四舍五入）
print("%.1f" % 3.141592653589793) # 3.1（进行了截断并四舍五入）
print("%.0f" % 3.54) # 4（进行了截断并四舍五入）

# 这与浮点数隐式转换为整数不同，浮点数隐式转换为整数会直接舍弃掉小数部分不会进行四舍五入。
print("%d" % 3.54) # 3（直接舍弃小数部分）

# m 的总位数 = 整数位数 + 小数点 + 小数点后位数
print("%6.3f。" % 3.52) #  3.520。（右对齐，总位数为5，左补1个空格，小数点后3位，小数点后3位不足，自动补0）
print("%-6.3f。" % 3.52) # 3.520 。（左对齐，总位数为5，右补1个空格，小数点后3位，小数点后3位不足，自动补0）
print("%2.3f。" % 3.52) # 3.520。（右对齐，总位数为4，超过总位数因此不作用，小数点后3位，小数点后3位不足，自动补0）